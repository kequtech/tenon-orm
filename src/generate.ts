import { defaultCodecs } from '@kequtech/pgclear';
import type { Connection } from './connection.js';
import { readTables, type CatalogClient } from './generation/catalog.js';
import { renderDatabase } from './generation/render.js';
import { domainSummaries, schemaSummary, tableSummary } from './generation/schema-summary.js';
import { withMigrationLock } from './migrations/connection.js';
import { migrationTable } from './migrations/history.js';
import { quote, validateName } from './sql.js';
import { plainObject } from './validation.js';
import { writeDefinitions } from './generation/output.js';

export interface GenerateOptions {
  readonly connection: Connection;
  readonly namespace?: string;
  readonly onWarning?: (message: string) => void | Promise<void>;
}

export interface GenerateTypesOptions {
  /** Output path, resolved from the working directory. */
  readonly out: string;
  /** Schema to inspect; defaults to public. */
  readonly namespace?: string;
  /** Reject missing or stale output without writing. Defaults to false. */
  readonly check?: boolean;
  readonly onWarning?: (message: string) => void | Promise<void>;
}

/** Generate with the owning database's connection and preserve exact file freshness checks. */
export async function generateTypes(
  connection: Connection,
  options: GenerateTypesOptions,
): Promise<void> {
  const config = plainObject(options, 'Generation options');
  for (const key of Object.keys(config)) {
    if (!['out', 'namespace', 'check', 'onWarning'].includes(key)) {
      throw new Error(`Unknown generation option: ${key}`);
    }
  }
  if (typeof config.out !== 'string' || !config.out.trim() || config.out.includes('\0')) {
    throw new Error('Generation out must be a nonempty file path.');
  }
  if (config.check !== undefined && typeof config.check !== 'boolean') {
    throw new Error('Generation check must be a boolean.');
  }
  if (options.namespace !== undefined) validateName(options.namespace);
  const source = await generateDefinitions({
    connection,
    ...(options.namespace !== undefined && { namespace: options.namespace }),
    ...(options.onWarning !== undefined && { onWarning: options.onWarning }),
  });
  await writeDefinitions(source, config.out, config.check === true);
}

/** Read one schema snapshot with default catalog codecs and the selected application read mappings. */
export async function generateDefinitions(options: GenerateOptions): Promise<string> {
  if (options.onWarning !== undefined && typeof options.onWarning !== 'function') {
    throw new Error('onWarning must be a function.');
  }
  const warn = options.onWarning ?? ((message: string) => console.warn('Warning: ' + message));
  return withMigrationLock(options, 'shared', (client, namespace) =>
    client.transaction(
      async (transaction) => {
        const catalog: CatalogClient = {
          query: (text, values = []) =>
            transaction.queryClassic(text, values, { codecs: defaultCodecs }),
        };
        const schema = await catalog.query(
          'SELECT 1 FROM pg_catalog.pg_namespace WHERE nspname = $1',
          [namespace],
        );
        if (!schema.rows.length) throw new Error(`Schema ${quote(namespace)} does not exist.`);
        await catalog.query(`SET LOCAL search_path TO pg_catalog, ${quote(namespace)}`);
        await catalog.query('SET LOCAL quote_all_identifiers TO off');
        await catalog.query('SET LOCAL standard_conforming_strings TO on');
        const tables = await readTables(catalog, namespace, [migrationTable]);
        const summaries = [];
        for (const table of tables) {
          summaries.push(await tableSummary(catalog, table.oid, table.name));
        }
        const domains = await domainSummaries(
          catalog,
          tables.flatMap((table) => table.columns.map((column) => column.declaredOid)),
        );
        const warnings: string[] = [];
        const types = renderDatabase(tables, namespace, transaction.codecs, (message) =>
          warnings.push(message),
        );
        for (const warning of warnings) await warn(warning);
        return `// Generated by Tenon from the PostgreSQL schema. Do not edit.\n\n${schemaSummary([...domains, ...summaries])}${types}`;
      },
      { isolation: 'repeatable read', readOnly: true },
    ),
  );
}
