import { readTables } from './generation/catalog.js';
import { renderRowTypes } from './generation/row-types.js';
import { domainSummaries, schemaSummary, tableSummary } from './generation/schema-summary.js';
import type { DatabaseToolOptions } from './migrations/connection.js';
import { withMigrationLock } from './migrations/connection.js';
import { readMigrations } from './migrations/files.js';
import { migrationState } from './migrations/history.js';
import { quote } from './sql.js';

export interface GenerateOptions extends DatabaseToolOptions {
  /** Receives generation warnings; defaults to console.warn. */
  readonly onWarning?: (message: string) => void;
}

/** Read-only introspection. Output needs no runtime imports or schema registration. */
export async function generateDefinitions(options: GenerateOptions): Promise<string> {
  const onWarning = options.onWarning ?? ((message: string) => console.warn(`Warning: ${message}`));
  const migrations = await readMigrations(options.directory);
  return withMigrationLock(options, 'shared', async (client, namespace) => {
    await client.query('BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY');
    // Keep catalog deparsing stable across connection settings and replay schemas.
    // Transaction-local settings are restored before returning a borrowed client.
    await client.query(`SET LOCAL search_path TO pg_catalog, ${quote(namespace)}`);
    await client.query('SET LOCAL quote_all_identifiers TO off');
    await client.query('SET LOCAL standard_conforming_strings TO on');
    const applied = await migrationState(client, namespace, migrations);
    if (applied.length !== migrations.length) {
      onWarning(
        `${migrations.length - applied.length} pending migration(s); generating definitions for the current database schema after ${applied.at(-1)?.id ?? 'no applied migrations'}.`,
      );
    }
    const definitions = await readTables(client, namespace);
    const summaries: string[] = [];
    for (const table of definitions) {
      summaries.push(await tableSummary(client, table.oid, table.name));
    }
    const domains = await domainSummaries(
      client,
      definitions.flatMap((table) => table.columns.map((column) => column.declaredOid)),
    );
    const types = renderRowTypes(definitions, namespace, onWarning);
    await client.query('COMMIT');
    const history = applied.map(({ id, checksum }) => ({ id, checksum }));
    return `// Generated by Tenon from the PostgreSQL schema at migrationHistory below. Do not edit.
// Commit this file; production migration commands do not regenerate it.

${schemaSummary([...domains, ...summaries])}export const migrationHistory = ${JSON.stringify(history)} as const;

${types}`;
  });
}
