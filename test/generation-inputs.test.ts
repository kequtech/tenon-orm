import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { join, resolve } from 'node:path';
import { after, before, test } from 'node:test';
import { pathToFileURL } from 'node:url';
import { promisify } from 'node:util';
import { Pool } from 'pg';
import { migrate, type SqlQuery } from '../src/index.js';
import { qualified } from '../src/sql.js';
import {
  assertTestDatabase,
  testConnection as connection,
  migrationProject,
  type MigrationProject,
} from './helpers/database.js';
import { checkGeneratedTypes, typeAssertions } from './helpers/generation.js';

const pool = new Pool({ connectionString: connection });
const project = migrationProject(pool);
const run = promisify(execFile);
before(() => assertTestDatabase(pool));
after(() => pool.end());

async function generatedQueries(
  options: MigrationProject,
  consumer: string,
): Promise<Record<string, SqlQuery>> {
  await checkGeneratedTypes(options, consumer);
  await run(process.execPath, [
    resolve('node_modules/typescript/bin/tsc'),
    '--project',
    join(options.directory, 'tsconfig.json'),
    '--noEmit',
    'false',
    '--outDir',
    join(options.directory, 'compiled'),
  ]);
  const module = (await import(
    pathToFileURL(join(options.directory, 'compiled/consumer.js')).href
  )) as { queries: Record<string, SqlQuery> };
  return module.queries;
}

test('generated mutation types enforce required fields and generated columns while executing defaults and patches', async () => {
  await project(
    {
      '0001_inputs.up.sql': `
        CREATE TABLE "Inputs" (
          id integer GENERATED ALWAYS AS IDENTITY,
          name text NOT NULL,
          score integer NOT NULL DEFAULT 7,
          bio text,
          caption text DEFAULT 'original',
          by_default integer GENERATED BY DEFAULT AS IDENTITY,
          serial_id serial,
          computed integer GENERATED ALWAYS AS (score + 1) STORED
        );`,
    },
    async (options) => {
      await migrate(options);
      const queries = await generatedQueries(
        options,
        `
        import { sql, identifier } from ${JSON.stringify(resolve('dist/index.js'))};
        import type { Rows } from './definitions.js';
        ${typeAssertions}
        type New = Rows.Insert['Inputs'];
        type Patch = Rows.Update['Inputs'];
        type ExpectedInsert = Assert<Equal<New, {
          id?: never; name: string; score?: number | undefined; bio?: string | null | undefined;
          caption?: string | null | undefined; by_default?: number | undefined;
          serial_id?: number | undefined; computed?: never;
        }>>;
        type ExpectedPatch = Assert<Equal<Patch, {
          id?: never; name?: string | undefined; score?: number | undefined;
          bio?: string | null | undefined; caption?: string | null | undefined;
          by_default?: number | undefined; serial_id?: number | undefined; computed?: never;
        }>>;
        const first: New = { name: 'first', score: undefined };
        const second: New = { name: 'second', score: 4, bio: null, caption: null,
          by_default: 20, serial_id: 30 };
        const patch: Patch = { name: undefined, score: undefined, bio: 'updated', by_default: 21 };
        const target = identifier(${JSON.stringify(options.namespace)}, 'Inputs');
        export const queries = {
          insert: sql\`INSERT INTO \${target} \${sql.insertValues<New>([first, second])} RETURNING *\`,
          update: sql\`UPDATE \${target} SET \${sql.assignments(patch)} WHERE name = 'second' RETURNING *\`,
        };
        function rejected(row: Rows['Inputs']) {
          // @ts-expect-error required fields cannot be omitted
          const missing: New = {};
          // @ts-expect-error required fields cannot use undefined
          const undefinedRequired: New = { name: undefined };
          // @ts-expect-error defaults do not make a column nullable
          const nullDefault: New = { name: 'test', score: null };
          // @ts-expect-error ALWAYS identity fields cannot receive values
          const identity: New = { name: 'test', id: 1 };
          // @ts-expect-error forbidden fields stay forbidden with exact optional properties
          const undefinedIdentity: New = { name: 'test', id: undefined };
          // @ts-expect-error computed fields cannot receive values
          const computed: New = { name: 'test', computed: 2 };
          // @ts-expect-error a full returned row contains forbidden generated fields
          const returned: New = row;
          // @ts-expect-error ALWAYS identity fields cannot be updated
          const updateIdentity: Patch = { id: 2 };
          // @ts-expect-error computed fields cannot be updated
          const updateComputed: Patch = { computed: 2 };
          // @ts-expect-error update fields retain their nullability
          const updateRequired: Patch = { name: null };
          // @ts-expect-error helper generic arguments can check fresh literals directly
          sql.insertValues<New>({ name: 'test', score: true });
        }
        `,
      );
      assert.deepEqual((await pool.query(queries.insert!.text, [...queries.insert!.values])).rows, [
        {
          id: 1,
          name: 'first',
          score: 7,
          bio: null,
          caption: 'original',
          by_default: 1,
          serial_id: 1,
          computed: 8,
        },
        {
          id: 2,
          name: 'second',
          score: 4,
          bio: null,
          caption: null,
          by_default: 20,
          serial_id: 30,
          computed: 5,
        },
      ]);
      assert.deepEqual((await pool.query(queries.update!.text, [...queries.update!.values])).rows, [
        {
          id: 2,
          name: 'second',
          score: 4,
          bio: 'updated',
          caption: null,
          by_default: 21,
          serial_id: 30,
          computed: 5,
        },
      ]);
    },
  );
});

test('domain defaults and nested NOT NULL constraints govern writes without narrowing returned rows', async () => {
  await project(
    {
      '0001_domains.up.sql': `
        CREATE DOMAIN "Required" AS integer NOT NULL CHECK (VALUE > 0);
        CREATE DOMAIN "NestedRequired" AS "Required";
        CREATE DOMAIN "Defaulted" AS integer NOT NULL DEFAULT 3;
        CREATE DOMAIN "NestedDefault" AS "Defaulted";
        CREATE DOMAIN "Loose" AS integer DEFAULT 5;
        CREATE TABLE "Inputs" (
          required "NestedRequired", defaulted "NestedDefault",
          overridden "NestedDefault" DEFAULT 9, loose "Loose"
        );`,
    },
    async (options) => {
      await migrate(options);
      await checkGeneratedTypes(
        options,
        `
        import type { Rows } from './definitions.js';
        ${typeAssertions}
        type Read = Assert<Equal<Rows['Inputs'], {
          required: number | null; defaulted: number | null;
          overridden: number | null; loose: number | null;
        }>>;
        type Write = Assert<Equal<Rows.Insert['Inputs'], {
          required: number; defaulted?: number | undefined;
          overridden?: number | undefined; loose?: number | null | undefined;
        }>>;
        const value: Rows.Insert['Inputs'] = { required: 1, defaulted: undefined, loose: null };
        const patch: Rows.Update['Inputs'] = { required: 2, defaulted: undefined, loose: null };
        // @ts-expect-error NOT NULL on a base domain requires the nested domain field
        const missing: Rows.Insert['Inputs'] = {};
        // @ts-expect-error a domain default permits omission, not explicit null
        const nullDefault: Rows.Insert['Inputs'] = { required: 1, defaulted: null };
        // @ts-expect-error updates respect inherited domain NOT NULL
        const nullRequired: Rows.Update['Inputs'] = { required: null };
        `,
      );
      const table = qualified(options.namespace, 'Inputs');
      assert.deepEqual(
        (await pool.query(`INSERT INTO ${table} (required) VALUES ($1) RETURNING *`, [1])).rows,
        [{ required: 1, defaulted: 3, overridden: 9, loose: 5 }],
      );
      await assert.rejects(pool.query(`INSERT INTO ${table} (required) VALUES ($1)`, [null]), {
        code: '23502',
      });
      await assert.rejects(pool.query(`INSERT INTO ${table} (required) VALUES ($1)`, [0]), {
        code: '23514',
      });
      await pool.query(`ALTER DOMAIN ${qualified(options.namespace, 'Required')} DROP NOT NULL`);
      await pool.query(
        `ALTER DOMAIN ${qualified(options.namespace, 'NestedDefault')} DROP DEFAULT`,
      );
      await assert.rejects(pool.query(`INSERT INTO ${table} (required) VALUES (1)`), {
        code: '23502',
      });
      assert.deepEqual(
        (
          await pool.query(
            `INSERT INTO ${table} (required, defaulted) VALUES (NULL, 4) RETURNING *`,
          )
        ).rows,
        [{ required: null, defaulted: 4, overridden: 9, loose: 5 }],
      );
      await checkGeneratedTypes(
        options,
        `
        import type { Rows } from './definitions.js';
        ${typeAssertions}
        type Changed = Assert<Equal<Rows.Insert['Inputs'], {
          required?: number | null | undefined; defaulted: number;
          overridden?: number | undefined; loose?: number | null | undefined;
        }>>;
        const patch: Rows.Update['Inputs'] = { required: null };
        // @ts-expect-error the removed domain default makes this nonnullable field required
        const missing: Rows.Insert['Inputs'] = {};
        `,
      );
    },
  );
});

test('generated write representations bind bigint, numeric, temporal, JSON and array inputs through pg', async () => {
  await project(
    {
      '0001_values.up.sql': `
        CREATE TYPE "Kind" AS ENUM ('reader', 'writer');
        CREATE TABLE "Values" (
          big bigint NOT NULL, decimal numeric NOT NULL, time timestamptz NOT NULL,
          payload jsonb NOT NULL, document json, bytes bytea NOT NULL, kind "Kind" NOT NULL,
          bigs bigint[] NOT NULL, decimals numeric[] NOT NULL, times timestamptz[] NOT NULL,
          payloads jsonb[] NOT NULL
        );`,
    },
    async (options) => {
      await migrate(options);
      const queries = await generatedQueries(
        options,
        `
        import { sql, identifier } from ${JSON.stringify(resolve('dist/index.js'))};
        import type { Rows, PgArray } from './definitions.js';
        ${typeAssertions}
        type New = Rows.Insert['Values'];
        type BigRead = Assert<Equal<Rows['Values']['big'], string>>;
        type TimeRead = Assert<Equal<Rows['Values']['time'], Date | number>>;
        type BigWrite = Assert<Equal<New['big'], string | bigint>>;
        type DecimalWrite = Assert<Equal<New['decimal'], string | number>>;
        type TimeWrite = Assert<Equal<New['time'], Date | string>>;
        type JsonWrite = Assert<Equal<New['payload'], string>>;
        type BigArray = Assert<Equal<New['bigs'], PgArray<string | bigint>>>;
        type DecimalArray = Assert<Equal<New['decimals'], PgArray<string | number>>>;
        type TimeArray = Assert<Equal<New['times'], PgArray<Date | string>>>;
        type JsonArray = Assert<Equal<New['payloads'], PgArray<string>>>;
        const value: New = {
          big: 9007199254740993n, decimal: '12345678901234567890.125', time: 'infinity',
          payload: JSON.stringify(['one', null]), document: 'null', bytes: Buffer.from([0, 255]), kind: 'reader',
          bigs: ['9007199254740993', 2n, null], decimals: ['1.25', 2.5, null],
          times: [new Date('2026-01-01T00:00:00Z'), '-infinity', null],
          payloads: [JSON.stringify({ nested: true }), 'null', null],
        };
        const target = identifier(${JSON.stringify(options.namespace)}, 'Values');
        const patch: Rows.Update['Values'] = { big: '2', decimal: 1.5, time: new Date('2026-01-01T00:00:00Z'),
          payload: 'null', document: null };
        export const queries = {
          insert: sql\`INSERT INTO \${target} \${sql.insertValues(value)} RETURNING *\`,
          update: sql\`UPDATE \${target} SET \${sql.assignments(patch)} RETURNING big, decimal, time, payload, document\`,
        };
        function rejected() {
          // @ts-expect-error arbitrary numbers are not canonical bigint inputs
          const big: New['big'] = 9007199254740993;
          // @ts-expect-error numeric temporal read values are not timestamp inputs
          const time: New['time'] = Infinity;
          // @ts-expect-error JSON inputs use serialized text, avoiding pg's array conversion
          const json: New['payload'] = ['one'];
          // @ts-expect-error nonnullable JSON does not accept SQL null
          const sqlNull: New['payload'] = null;
          // @ts-expect-error required JSON does not accept undefined
          const absent: New['payload'] = undefined;
          // @ts-expect-error enum inputs retain their database choices
          const kind: New['kind'] = 'other';
        }
        `,
      );
      assert.deepEqual((await pool.query(queries.insert!.text, [...queries.insert!.values])).rows, [
        {
          big: '9007199254740993',
          decimal: '12345678901234567890.125',
          time: Infinity,
          payload: ['one', null],
          document: null,
          bytes: Buffer.from([0, 255]),
          kind: 'reader',
          bigs: ['9007199254740993', '2', null],
          decimals: [1.25, 2.5, null],
          times: [new Date('2026-01-01T00:00:00Z'), -Infinity, null],
          payloads: [{ nested: true }, null, null],
        },
      ]);
      assert.deepEqual((await pool.query(queries.update!.text, [...queries.update!.values])).rows, [
        {
          big: '2',
          decimal: '1.5',
          time: new Date('2026-01-01T00:00:00Z'),
          payload: null,
          document: null,
        },
      ]);
    },
  );
});
