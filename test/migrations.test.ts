async function waitForAdvisoryWaiters(application: string, expected: number): Promise<void> {
  const deadline = Date.now() + 5000;
  let count = 0;
  do {
    const result = await pool.query<{ count: number }>(`
      SELECT count(*)::int AS count FROM pg_catalog.pg_locks l
      JOIN pg_catalog.pg_stat_activity a ON a.pid = l.pid
      WHERE l.locktype = 'advisory' AND NOT l.granted
        AND a.datname = current_database() AND a.application_name = $1`, [application]);
    count = result.rows[0]!.count;
    if (count === expected) return;
    await delay(10);
  } while (Date.now() < deadline);
  assert.fail(`Expected ${expected} waiting advisory locks, observed ${count}.`);
}

async function checkGeneratedTypes(options: GenerateOptions & { directory: string }, consumer: string): Promise<void> {
  // Compile a real consumer of newly generated types, not a textual snapshot of
  // declaration syntax. No package build or live connection is needed by the TypeScript consumer.
  const source = await generateDefinitions(options);
  await writeFile(join(options.directory, 'package.json'), '{"type":"module"}');
  await writeFile(join(options.directory, 'definitions.ts'), source);
  const filename = join(options.directory, 'consumer.ts');
  await writeFile(filename, consumer);
  const config = join(options.directory, 'tsconfig.json');
  await writeFile(config, JSON.stringify({
    compilerOptions: { noEmit: true, strict: true, exactOptionalPropertyTypes: true,
      noUncheckedIndexedAccess: true, skipLibCheck: true, target: 'ES2022', module: 'NodeNext',
      moduleResolution: 'NodeNext', types: ['node'], typeRoots: [resolve('node_modules/@types')],
    },
    files: ['consumer.ts'],
  }));
  await run(process.execPath, [resolve('node_modules/typescript/bin/tsc'), '--project', config]);
}

